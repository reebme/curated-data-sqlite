import sqlite3
from contextlib import contextmanager
from pathlib import Path

import pandas as pd


@contextmanager
def connection(db_file: Path):
    '''
    Open a db_file only if it exists. Otherwise raise OperationalError.
    Ensure foreign keys are on.
    Always close the connection.
    '''
    # resolve a path in case it's relative and change into uri format
    uri_db_file = db_file.resolve().as_uri()
    # connect do a db if it exists
    conn = sqlite3.connect(
            f"{uri_db_file}?mode=rw", 
            uri=True,
            autocommit=sqlite3.LEGACY_TRANSACTION_CONTROL,
            isolation_level="DEFERRED"
    )
    # ensure foreign keys
    try:
        conn.execute("pragma foreign_keys = on;")
        # transaction commits or rolls back
        with conn:    
            yield conn
    # always close the connection
    finally:
        conn.close()

def ensure_db(db_file: Path, db_schema_file: Path) -> None:
    '''
    Create a DB using the provided schema if it doesn't exist.
    The DB is created as one transaction which either comits or rolls back.
    It is assumed that schema has begin/commit.
    '''
    # if the db exists do nothing
    if db_file.is_file(): return
    
    # ensure the directory exists
    # create one with all the parents unless it already exists
    db_file.parent.mkdir(parents=True, exist_ok=True)
    try:
        conn = sqlite3.connect(db_file)
        try:
            conn.executescript(db_schema_file.read_text())
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()
    except Exception:
        # remove DB because it was not initialized correctly
        db_file.unlink(missing_ok=True)
        raise

def ensure_source(db_file: Path, source_code: str, source_name: str) -> None:
    with connection(db_file) as conn:
        # uses SQLite dialect ON CONFLICT clause
        # if constraints are violated it does nothing
        conn.execute(
            """
            INSERT INTO sources (
                source_code,
                source_name
            )
            VALUES (?, ?)
            ON CONFLICT DO NOTHING;
            """,
            (
                source_code,
                source_name
            )
        )
        # check source
        # there's a primary key constraint on source_code
        row = conn.execute(
            """
            select * from sources
            where source_code = ?;
            """,
            (source_code, )
        ).fetchone()

        if row is None:
            raise sqlite3.IntegrityError(
                f"Source {source_code!r} was not found after insertion."
            )

        if row != (source_code, source_name):
            raise ValueError(
                f"source_code: {row[0]!r} has an unexpected name {row[1]!r}."
            )


def insert_new_data(conn,
                    df: pd.DataFrame,
                    table_name: str,
                    key_cols: list[str],
                    logical_key_cols: list[str] = None) -> int:
    """
    Inserts new data into the table `table_name`.
    Conflicts are skipped on insert (function is safe to rerun).
    Does not commit.
    Returns no of inserted rows.
    Safe to rerun.
    For ommited rows it checks data integrity.

    key_cols are the PK columns of the table `table_name`.
    They do not have to exist in df, when they are autogenerated by the DB.
    logical_key_cols have to exist in the df if provided.
    """
    # check if there are duplicate keys in the dataframe
    if set(key_cols).issubset(df.columns) and df[key_cols].duplicated().any():
        raise ValueError(
            "Duplicate key entries."
        )

    # check if there are duplicate logical key rows in the dataframe
    if logical_key_cols:
        if set(logical_key_cols).issubset(df.columns):
            if df[logical_key_cols].duplicated().any():
                raise ValueError(
                    "Duplicate logical key entries."
                )
        else:
            raise ValueError(
                f"One of the columns {logical_key_cols} not in the provided dataframe."
            )

    # prepare the sql statement
    sql = (
        f"insert into {table_name} ({", ".join(df.columns)}) "
        f"values ({", ".join("?" * len(df.columns))}) "
        "on conflict do nothing;"
    )

    # execute the sql
    cur = conn.executemany(
        sql,
        df.itertuples(index=False, name=None)
    )
    # fetch no of inserted rows
    inserted = cur.rowcount

    # inspect the conflicts
    # 1. row can exist and be the same
    # 2. key mignt exist but the row differs
    # 3. key might exist in the dataframe and not the table
    # the cases which need inspection are 2. and 3.
    if inserted != len(df):
        row_str = f"({', '.join('?' * df.shape[1])})"
        columns_str = ', '.join(df.columns)

        # keys with '=' so the planner can use the unique index;
        # the rest with 'is' so NULLs (e.g. wave_id) compare as equal
        not_key_cols = [c for c in df.columns if c not in key_cols]
        #match = (
        #    " and ".join([(f"incoming.{c} = t.{c}") for c in key_cols])
        #)
        if set(key_cols).issubset(df.columns):
            key_cols_match_list = [(f"incoming.{c} = t.{c}") for c in key_cols]
        else:
            key_cols_match_list = []
        match = " and ".join([*key_cols_match_list, *[(f"incoming.{c} is t.{c}") for c in not_key_cols]])

        # get the limit for no of variables
        no_cols = df.shape[1]
        # sqlite3.SQLITE_LIMIT_VARIABLE_NUMBER = n * d, where (n,d) is the shape of a table
        # hence max no of rows = sqlite3.SQLITE_LIMIT_VARIABLE_NUMBER // no_cols
        # no_cols < SQLITE_LIMIT_COLUMN < SQLITE_LIMIT_VARIABLE_NUMBER
        batch_size = conn.getlimit(sqlite3.SQLITE_LIMIT_VARIABLE_NUMBER) // no_cols
        for start in range(0, len(df), batch_size):
            df_batch = df.iloc[start:start + batch_size]
            sql = (
                f"with incoming({columns_str}) as ( "
                f"values {", ".join([row_str] * len(df_batch))} ) "
                f"select {columns_str} from incoming "
                f"where not exists ( "
                f"select 1 from {table_name} as t "
                f"where {match} );"
            )
            params = [v for t in df_batch.itertuples(index=False, name=None) for v in t]
            problems = conn.execute(sql, params).fetchall()

            if problems:
                problem_rows = problems[:5]
                problem_display = "\n".join([
                    " | ".join(df.columns),
                    *(" | ".join(str(value) for value in row) for row in problem_rows),
                ])
                raise ValueError(
                    f"Missing or differing rows in {table_name} "
                    f"(first {len(problem_rows)} problem rows in this batch):\n"
                    f"{problem_display}"
                )

    return inserted
